"""
make_synthetic.py
=================
Generate a SYNTHETIC, OFFLINE stand-in for the four raw series, so the whole
pipeline can be run and tested without internet access.

#####################################################################
#  THE NUMBERS THIS PRODUCES ARE FAKE. They exist only to prove the  #
#  code runs and to show the shape of the outputs. Any backtest       #
#  result from synthetic data is MEANINGLESS as market evidence.      #
#  Replace it with real data (src/data_download.py) before drawing    #
#  any conclusion about gold.                                         #
#####################################################################

The generator deliberately builds in a *mild* regime structure (gold drifts a
little differently when simulated volatility / real yields / fear differ) so the
clustering and backtest have something to find — but the effect is small and
noisy, mirroring the workbook's "honest expectation" of little or no edge.

    python -m src.make_synthetic
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from . import config


def _save(df: pd.DataFrame, name: str) -> None:
    path = config.DATA_RAW / name
    df.to_csv(path, index=False)
    print(f"  SYNTHETIC -> {name:16s} {len(df):>6,} rows")


def main(seed: int = 7) -> None:
    rng = np.random.default_rng(seed)

    # Business-day calendar from the configured start to "today".
    dates = pd.bdate_range(config.GOLD_START, pd.Timestamp.today().normalize())
    n = len(dates)

    # --- latent macro drivers (random walks with realistic ranges) ---------- #
    real_yield = 0.5 + np.cumsum(rng.normal(0, 0.02, n))      # ~ -1%..3%
    real_yield = np.clip(real_yield, -1.5, 3.5)

    dollar = 100 + np.cumsum(rng.normal(0, 0.15, n))          # broad USD index
    # VIX: mean-reverting, positive, with occasional spikes.
    vix = np.empty(n)
    vix[0] = 18.0
    for t in range(1, n):
        shock = rng.normal(0, 1.0) + (8.0 if rng.random() < 0.004 else 0.0)
        vix[t] = max(9.0, 0.97 * vix[t - 1] + 0.03 * 18.0 + shock)

    # --- gold returns depend weakly on the drivers (the "regime" effect) ---- #
    # Higher fear -> slightly higher gold drift; higher real yield -> slightly
    # lower drift. Base daily vol scales up with VIX. All effects are small.
    ry_chg = np.gradient(real_yield)
    daily_vol = 0.008 + 0.00035 * (vix - vix.mean())
    daily_vol = np.clip(daily_vol, 0.004, 0.05)
    drift = (
        0.0001
        + 0.00004 * (vix - vix.mean())       # fear premium
        - 0.004 * ry_chg                      # real-yield headwind
    )
    gold_ret = rng.normal(drift, daily_vol)
    gold_price = 550.0 * np.exp(np.cumsum(gold_ret))          # ~2006 gold level

    # Macro series are published to FRED on their own (slightly sparser) days;
    # drop a few rows at random to mimic holidays / release gaps (Pitfall #7/#8).
    def _macro_frame(values: np.ndarray) -> pd.DataFrame:
        keep = rng.random(n) > 0.02            # drop ~2% of days
        return pd.DataFrame({"date": dates[keep], "value": values[keep]})

    _save(pd.DataFrame({"date": dates, "value": gold_price}), "gold.csv")
    _save(_macro_frame(real_yield), "real_yield.csv")
    _save(_macro_frame(dollar), "dollar.csv")
    _save(_macro_frame(vix), "vix.csv")

    # A breadcrumb so nobody mistakes this for real data downstream.
    (config.DATA_RAW / "SYNTHETIC.txt").write_text(
        "These raw files were generated by src/make_synthetic.py.\n"
        "They are FAKE. Delete this file and run src/data_download.py for real data.\n"
    )
    print("Synthetic data written. (FAKE — for pipeline testing only.)")


if __name__ == "__main__":
    main()
